# safety/program_safety.py

import time

from utils import logger


class ProgramSafety:

    """
    Program-level watchdog interface.

    STA (NEW_HDC.STA):
        Heartbeat bit generated by Python. The value toggles 0/1
        periodically while the main program loop is alive.

        DCS should monitor the time since the last STA transition.
        If STA does not change within the configured watchdog timeout,
        DCS should treat the Python application as unavailable.

    There is intentionally NO INF/program information signal.
    """

    def __init__(
        self,
        opc,
        heartbeat_interval=1.0
    ):

        self.opc = opc
        self.heartbeat_interval = float(heartbeat_interval)

        self.heartbeat = False
        self.last_heartbeat_time = None
        self.last_write_ok = False

    # ==================================================
    # HEARTBEAT
    # ==================================================

    def update_heartbeat(self, force=False):
        """Toggle and write NEW_HDC.STA when its interval expires."""

        now = time.monotonic()

        if (
            not force
            and self.last_heartbeat_time is not None
            and now - self.last_heartbeat_time < self.heartbeat_interval
        ):
            return False

        self.heartbeat = not self.heartbeat
        value = int(self.heartbeat)

        try:
            self.opc.write(
                "program_safety_status",
                value
            )

            self.last_heartbeat_time = now
            self.last_write_ok = True

            logger.info(
                f"[WATCHDOG] STA heartbeat -> {value}"
            )

            return True

        except Exception as e:
            self.last_write_ok = False

            # Do not crash the HDC sequence merely because a heartbeat
            # write failed. If STA stops changing, the DCS watchdog
            # will detect the missing heartbeat.
            logger.error(
                f"[WATCHDOG] STA WRITE FAILED: "
                f"type={type(e).__name__}, error={e!r}"
            )

            return False

    # ==================================================
    # SHUTDOWN
    # ==================================================

    def shutdown(self):
        """Best-effort final STA write during graceful shutdown."""

        try:
            # Force a transition so the DCS can immediately see that
            # the application reached a graceful shutdown point.
            self.heartbeat = not self.heartbeat
            value = int(self.heartbeat)

            self.opc.write(
                "program_safety_status",
                value
            )

            logger.info(
                f"[WATCHDOG] Final STA heartbeat -> {value}"
            )

        except Exception as e:
            logger.error(
                f"[WATCHDOG] Final STA write failed: {e!r}"
            )
